import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { extname, join, relative, resolve } from 'node:path';
import { ROOT, filesUnder, fingerprint, inside, parseSrt, positive, probe, toSrt } from './lib.mjs';

export const FONT = '"Microsoft YaHei", "Noto Sans CJK SC", "PingFang SC", sans-serif';
const json = file => JSON.parse(readFileSync(file, 'utf8').replace(/^\uFEFF/, ''));
export const saveJson = (file, value) => writeFileSync(file, JSON.stringify(value, null, 2) + '\n', 'utf8');
const uri = (base, file) => relative(base, file).split(/[\\/]/).map(encodeURIComponent).join('/');
const escapeHtml = value => String(value).replace(/[&<>"']/g, ch => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[ch]));

export function validateCaptions(segments, duration, allowEmpty = false) {
  if (!Array.isArray(segments) || (!allowEmpty && !segments.length)) throw new Error('No timed transcript. Run transcribe or import an SRT with --srt.');
  segments.forEach((cue, i) => {
    if (typeof cue.start !== 'number' || typeof cue.end !== 'number' || !Number.isFinite(cue.start) || !Number.isFinite(cue.end) || cue.start < 0 || cue.end <= cue.start || cue.end > duration + .05 || typeof cue.text !== 'string' || !cue.text.trim()) throw new Error(`Invalid transcript cue ${i + 1}.`);
    if (i && cue.start < segments[i - 1].end - .001) throw new Error(`Transcript cues overlap at cue ${i + 1}.`);
  });
}

export function loadProject(dir, { draft = false, ffprobe } = {}) {
  const project = json(join(dir, 'project.json'));
  if (project.version !== 1 || typeof project.title !== 'string' || !project.title.trim()) throw new Error('Expected project.json version 1 and a non-empty title.');
  const duration = positive(project.duration, 'duration');
  for (const key of ['width', 'height', 'fps']) positive(project[key], key, true);
  if (project.width % 2 || project.height % 2 || project.width > 8192 || project.height > 8192 || project.fps > 120) throw new Error('Use even dimensions up to 8192 and fps up to 120.');
  if (typeof project.font !== 'string' || !project.font.trim()) throw new Error('A local CSS font stack is required.');
  const subtitles = project.subtitles;
  if (!subtitles || typeof subtitles.enabled !== 'boolean' || typeof subtitles.font !== 'string' || !subtitles.font.trim()) throw new Error('Invalid subtitles configuration.');
  positive(subtitles.fontSize, 'subtitles.fontSize'); positive(subtitles.maxLines, 'subtitles.maxLines', true);
  if (subtitles.maxLines > 3 || subtitles.fontSize > project.height * .15) throw new Error('Subtitle settings exceed the safe caption band.');
  const audio = inside(dir, project.audio), audioInfo = probe(audio, ffprobe);
  if (Math.abs(duration - audioInfo.duration) > .05) throw new Error(`Duration ${duration}s differs from audio ${audioInfo.duration}s. Use the audio duration.`);
  if (!Array.isArray(project.scenes) || !project.scenes.length) throw new Error('At least one scene is required.');
  const ids = new Set();
  let cursor = 0;
  for (const scene of project.scenes) {
    if (!/^[a-zA-Z0-9_-]+$/.test(scene.id) || ids.has(scene.id)) throw new Error(`Invalid/duplicate scene id: ${scene.id}`);
    ids.add(scene.id);
    if (!Number.isFinite(scene.start) || !Number.isFinite(scene.end) || Math.abs(scene.start - cursor) > .001 || scene.end <= scene.start || scene.end > duration + .001) throw new Error(`Scenes must cover the audio without gaps/overlaps: ${scene.id}`);
    if (!['cut', 'wipe'].includes(scene.transition)) throw new Error(`Unknown transition: ${scene.id}`);
    if (!['draft', 'ready'].includes(scene.status) || (!draft && scene.status !== 'ready')) throw new Error(`Scene ${scene.id} is unfinished. Implement its animation and set status to ready; use --draft for previews.`);
    if (!existsSync(inside(dir, scene.module))) throw new Error(`Scene module missing: ${scene.module}`);
    cursor = scene.end;
  }
  if (Math.abs(cursor - duration) > .001) throw new Error('Last scene must end at the audio duration.');
  const transcript = json(join(dir, 'transcript.json'));
  validateCaptions(transcript.segments, duration, draft);
  return { project, transcript, audio, audioInfo };
}

export function importSrt(dir, file) {
  const project = json(join(dir, 'project.json'));
  const segments = parseSrt(readFileSync(file, 'utf8'));
  validateCaptions(segments, project.duration);
  const transcript = { source: 'imported-srt', language: 'unknown', segments };
  saveJson(join(dir, 'transcript.json'), transcript);
  return transcript;
}

export function buildProject(dir, options = {}) {
  const data = loadProject(dir, options);
  const runtime = { ...data.project, captions: data.transcript.segments };
  writeFileSync(join(dir, 'project-data.js'), `// Generated by video build; edit project.json and transcript.json instead.\nwindow.VIDEO_PROJECT = ${JSON.stringify(runtime, null, 2)};\n`, 'utf8');
  writeFileSync(join(dir, 'subtitles.srt'), toSrt(data.transcript.segments), 'utf8');
  writeFileSync(join(dir, 'transcript.txt'), data.transcript.segments.map(cue => cue.text).join('\n') + '\n', 'utf8');
  const scripts = [join(ROOT, 'node_modules/p5/lib/p5.min.js'), join(ROOT, 'node_modules/p5.brush/dist/p5.brush.js'), join(dir, 'project-data.js'), ...['core.js', 'clawd.js', 'cast.js', 'props.js', 'video-timeline.js'].map(file => join(ROOT, 'src', file)), ...data.project.scenes.map(scene => inside(dir, scene.module))];
  const html = `<!doctype html>
<html lang="zh-CN"><head><meta charset="utf-8"><title>${escapeHtml(data.project.title)}</title>
<style>html,body{margin:0;background:#1b1820;color:#eee;font:14px system-ui,sans-serif}main{padding:12px;display:grid;gap:10px}#out{max-width:100%;max-height:80vh;width:auto;height:auto}.p5Canvas{display:none!important}.bar{display:flex;gap:12px;align-items:center}#scrub{flex:1}audio{width:100%}</style></head>
<body><main><canvas id="out" width="${data.project.width}" height="${data.project.height}"></canvas>
<div class="bar"><input id="scrub" type="range" min="0" max="${data.project.duration}" step="${1 / data.project.fps}" value="0"><span id="tt">loading…</span></div>
<audio id="audio" controls preload="metadata" src="${uri(dir, data.audio)}"></audio></main>
<script>const CAST = {};</script>
${scripts.map(file => `<script src="${uri(dir, file)}"></script>`).join('\n')}
</body></html>\n`;
  writeFileSync(join(dir, 'studio.html'), html, 'utf8');
  const signature = fingerprint([...filesUnder(dir, new Set(['out', '.git', '__pycache__'])), ...scripts.filter(file => !file.startsWith(dir)), join(ROOT, 'scripts/render-video.mjs'), join(ROOT, 'package-lock.json')]);
  return { ...data, signature, entry: join(dir, 'studio.html'), frames: join(dir, 'out', 'frames', signature.slice(0, 16)) };
}

export function initProject(dir, args) {
  if (existsSync(dir)) throw new Error(`Project directory already exists; choose another --name/--dir: ${dir}`);
  if (typeof args.audio !== 'string') throw new Error('init requires --audio <MP3 path>.');
  const source = resolve(args.audio), audioInfo = probe(source, args.ffprobe);
  const width = positive(args.width ?? 1920, 'width', true), height = positive(args.height ?? 1080, 'height', true), fps = positive(args.fps ?? 24, 'fps', true);
  const audio = 'narration' + (extname(source).toLowerCase() || '.mp3');
  const project = {
    version: 1, title: args.title || args.name || '科普视频', audio, duration: audioInfo.duration,
    width, height, fps, font: FONT,
    subtitles: { enabled: true, font: FONT, fontSize: Math.round(width / 40), maxLines: 2 },
    scenes: [{ id: 'intro', start: 0, end: audioInfo.duration, module: 'scenes/intro.js', transition: 'cut', status: 'draft' }],
  };
  // Validate supplied captions and dimensions before creating any task files.
  if (width % 2 || height % 2 || width > 8192 || height > 8192 || fps > 120) throw new Error('Use even dimensions up to 8192 and fps up to 120.');
  const segments = args.srt ? parseSrt(readFileSync(resolve(args.srt), 'utf8')) : [];
  validateCaptions(segments, audioInfo.duration, !args.srt);
  mkdirSync(join(dir, 'scenes'), { recursive: true });
  copyFileSync(source, join(dir, audio));
  saveJson(join(dir, 'project.json'), project);
  saveJson(join(dir, 'transcript.json'), { source: args.srt ? 'imported-srt' : 'pending', language: args.language || 'zh', segments });
  writeFileSync(join(dir, 'STORYBOARD.md'), `# ${project.title}\n\n音频：${audio}；时长：${audioInfo.duration.toFixed(3)} 秒；画幅：${width}×${height}；帧率：${fps}。\n\n先从 transcript.json 读取带时间戳的实际旁白，再用概念、因果、比较或过程拆分场景。\n\n| 起止秒 | 对应旁白 | 讲解目标 | 主体与动作 | 镜头与转场 | 模块 |\n|---|---|---|---|---|---|\n\n当前 intro.js 是用于验证环境的占位画面，尚未制作。\n`, 'utf8');
  writeFileSync(join(dir, 'scenes', 'intro.js'), `// Scaffold only. Replace with visuals that explain the actual narration.\n(() => {\n  function draft(t, lt, dur) {\n    paint(ellPts(W / 2, H * .42, W * .22, H * .22, 28, 4), { wash: PAL.sky, ink: null });\n    const x = W / 2 + Math.sin(t * 2) * W * .03;\n    paint(ellPts(x, H * .42, H * .09, H * .09, 24, 2), { wash: PAL.teal, ink: PAL.ink });\n    letter('待制作：' + window.VIDEO_PROJECT.title, W / 2, H * .72, W * .028, PAL.ink, { ink: false });\n  }\n  chapter('intro', 0, DUR, [[0, draft]]);\n})();\n`, 'utf8');
  buildProject(dir, { draft: true, ffprobe: args.ffprobe });
  return project;
}
